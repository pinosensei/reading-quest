/* Helpers (no need to edit) */
window.RQWords = {
  // All words of one level as objects: { en, jp, pic, theme }
  list(level) {
    const groups = window.RQ_WORDS[level] || window.RQ_WORDS.starter;
    const out = [];
    Object.keys(groups).forEach((theme) => {
      groups[theme].forEach(([en, jp, pic]) => out.push({ en, jp, pic, theme }));
    });
    return out;
  },
  // Only words that have a picture
  withPictures(level) { return this.list(level).filter((w) => w.pic); },
  // Only single short words (good for spelling / first sounds)
  simple(level, maxLen = 6) {
    return this.list(level).filter((w) => /^[a-z]+$/.test(w.en) && w.en.length <= maxLen);
  }
};
